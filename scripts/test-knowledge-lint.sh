#!/bin/sh
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
shipped="$root/skills/repo-knowledge/scripts/knowledge-lint.sh"
work=$(mktemp -d "${TMPDIR:-/tmp}/test-knowledge-lint.XXXXXX")
trap 'rm -rf "$work"' EXIT
failures=0

unset GIT_DIR GIT_WORK_TREE GIT_INDEX_FILE
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
export GIT_AUTHOR_NAME=Test GIT_AUTHOR_EMAIL=test@example.com
export GIT_COMMITTER_NAME=Test GIT_COMMITTER_EMAIL=test@example.com

fail() {
  echo "test-knowledge-lint: $1" >&2
  failures=$((failures + 1))
}

stamp='As of abc1234, 2026-11-12'

node() {
  {
    echo "---"
    echo "code:"
    echo "  - $3"
    echo "skills: []"
    echo "api: []"
    if [ -n "$4" ]; then
      echo "related:"
      echo "  - $4"
    else
      echo "related: []"
    fi
    if [ -n "$5" ]; then
      echo "decisions:"
      echo "  - $5"
    else
      echo "decisions: []"
    fi
    echo "---"
    echo
    echo "# $2"
    echo
    echo "## What it is"
    echo
    echo "$2 lives here. $stamp."
  } >"$dir/docs/features/$1.md"
}

fixture() {
  dir="$work/$1"
  mkdir -p "$dir/scripts" "$dir/src/invoices" "$dir/src/billing" "$dir/docs/adr" "$dir/docs/features"
  git init -q -b main "$dir"
  cp "$shipped" "$dir/scripts/knowledge-lint.sh"
  printf 'export const a = 1\n' >"$dir/src/invoices/a.ts"
  printf 'export const b = 2\n' >"$dir/src/billing/b.ts"
  printf '# Numbering\n' >"$dir/docs/adr/0001-numbering.md"
  node invoices Invoices 'src/invoices/**' billing docs/adr/0001-numbering.md
  node billing Billing 'src/**/b.{ts,tsx}' '' ''
  git -C "$dir" add -A
}

lint() {
  status=0
  (cd "$dir" && ./scripts/knowledge-lint.sh "$@") >"$work/out" 2>"$work/err" || status=$?
}

expect() {
  if [ "$status" -ne "$2" ]; then
    fail "$1: exit $status, wanted $2: $(cat "$work/out" "$work/err")"
  elif [ -n "${3:-}" ] && ! cat "$work/out" "$work/err" | grep -qF -- "$3"; then
    fail "$1: output lacks '$3': $(cat "$work/out" "$work/err")"
  fi
}

cat >"$work/expected-index" <<'EOF'
# Knowledge index

Generated by `scripts/knowledge-lint.sh --write` from the nodes in `docs/features/`. Edit the nodes, never this file. CI runs `scripts/knowledge-lint.sh`, which fails on a code glob that matches no file, a dead link, or a source area no node covers.

Decisions: [docs/adr/](../adr/).

## Paths

| Path | Nodes |
| --- | --- |
| `src/**/b.{ts,tsx}` | [billing](../features/billing.md) |
| `src/invoices/**` | [invoices](../features/invoices.md) |

## Nodes

| Node | Title |
| --- | --- |
| [billing](../features/billing.md) | Billing |
| [invoices](../features/invoices.md) | Invoices |
EOF

fixture clean
lint --write
expect "case 1 --write" 0 "wrote docs/knowledge/index.md"
cmp -s "$work/expected-index" "$dir/docs/knowledge/index.md" || fail "case 1: the index differs from the expected one: $(diff "$work/expected-index" "$dir/docs/knowledge/index.md" || :)"
lint
expect "case 1 plain run" 0 "knowledge-lint: ok (2 nodes, 2 distinct globs)"
lint --write
expect "case 1 second --write" 0 "knowledge-lint: ok"
if grep -q '^wrote' "$work/out"; then
  fail "case 1: a second --write rewrote an unchanged index"
fi

fixture glossary
mkdir -p "$dir/docs/knowledge"
printf '# Glossary\n' >"$dir/docs/knowledge/GLOSSARY.md"
lint --write
expect "case 1b glossary" 0 "knowledge-lint: ok"
grep -qxF 'Glossary: [GLOSSARY.md](GLOSSARY.md). Decisions: [docs/adr/](../adr/).' "$dir/docs/knowledge/index.md" ||
  fail "case 1b: the index does not point to the glossary and the decisions"

fixture noglob
node billing Billing 'src/nope/**' '' ''
lint --write
line=$(grep -n 'src/nope' "$dir/docs/features/billing.md" | cut -d: -f1)
lint
expect "case 2 glob matching nothing" 1 "docs/features/billing.md:$line: src/nope/** matches no file"

fixture links
{
  echo
  echo '[x](../missing.md) [y](https://example.com) [z](#top)'
  echo '[ok](invoices.md "the invoices") [root](/docs/adr/0001-numbering.md)'
  echo '`[inline](nowhere.md)`'
  printf '%s\n' '```'
  echo '[fenced](nowhere.md)'
  printf '%s\n' '```'
} >>"$dir/docs/features/billing.md"
lint --write
lint
expect "case 3 dead link" 1 "dead link ../missing.md"
if grep -qE 'nowhere|example.com|#top|invoices.md|0001-numbering' "$work/err"; then
  fail "case 3: a link that resolves, or that is skipped, was reported: $(cat "$work/err")"
fi

fixture area
lint --write
mkdir -p "$dir/src/reports"
printf 'export const r = 3\n' >"$dir/src/reports/r.ts"
lint
expect "case 4 uncovered source area" 1 "src/reports: no node covers this source area"
mkdir -p "$dir/docs/knowledge"
printf '!src/reports\n' >"$dir/docs/knowledge/source-roots.txt"
lint
expect "case 4 excluded source area" 0 "knowledge-lint: ok"
printf 'src\n!src/reports\nlibs\n' >"$dir/docs/knowledge/source-roots.txt"
lint
expect "case 4 root without files" 1 "docs/knowledge/source-roots.txt:3: libs has no files"

fixture stale
lint --write
before=$(cat "$dir/docs/knowledge/index.md")
node billing Billing 'src/billing/b.ts' '' ''
lint
expect "case 5 stale index" 1 "docs/knowledge/index.md is out of date; run scripts/knowledge-lint.sh --write"
[ "$(cat "$dir/docs/knowledge/index.md")" = "$before" ] || fail "case 5: a plain run changed the index"

fixture ghost
node invoices Invoices 'src/invoices/**' ghost docs/adr/0001-numbering.md
lint --write
lint
expect "case 6 related node that does not exist" 1 "related node ghost does not exist"
fixture ghostadr
node invoices Invoices 'src/invoices/**' billing docs/adr/0009-none.md
lint --write
lint
expect "case 6 decision that does not exist" 1 "decision docs/adr/0009-none.md does not exist"

fixture undated
stamp='Nothing dated here'
node billing Billing 'src/**/b.{ts,tsx}' '' ''
stamp='As of abc1234, 2026-11-12'
lint --write
lint
expect "case 7 undated node" 1 "docs/features/billing.md: no dated claim"

fixture badkey
{
  echo "---"
  echo "codes:"
  echo "  - src/billing/**"
  echo "---"
  echo
  echo "# Billing"
  echo
  echo "Billing. $stamp."
} >"$dir/docs/features/billing.md"
lint --write
expect "case 8 unknown key" 1 "docs/features/billing.md:2: unknown key codes"
[ ! -e "$dir/docs/knowledge/index.md" ] || fail "case 8: --write wrote an index although a node was invalid"

fixture notitle
{
  echo "---"
  echo "code: []"
  echo "---"
  echo
  echo "Billing. $stamp."
} >"$dir/docs/features/billing.md"
lint
expect "case 8b node without a title" 1 "docs/features/billing.md: no # title"

fixture open
{
  echo "---"
  echo "code: []"
  echo "# Billing"
} >"$dir/docs/features/billing.md"
lint
expect "case 8c frontmatter never closed" 1 "docs/features/billing.md:1: frontmatter is not closed"

fixture bare
printf '# Billing\n' >"$dir/docs/features/billing.md"
lint
expect "case 8d node without frontmatter" 1 "docs/features/billing.md:1: no frontmatter"

fixture relative
node billing Billing './src/x' '' ''
lint --write
expect "case 9 glob not relative to the root" 1 "./src/x must be relative to the repo root"

fixture unsupported
node billing Billing 'src/[a]/**' '' ''
lint
expect "case 9b glob with a character class" 1 "uses an unsupported character"

fixture empty
rm "$dir/docs/features/"*.md
lint
expect "case 9c no nodes" 1 "no nodes in docs/features/"

fixture parens
printf '# Parens\n' >"$dir/docs/adr/a_(b).md"
{
  echo
  echo '[p](../adr/a_(b).md) [q](../adr/c_(d).md)'
} >>"$dir/docs/features/billing.md"
lint --write
lint
expect "case 3b link with parentheses" 1 "dead link ../adr/c_(d).md"
if grep -qF 'a_(b)' "$work/err"; then
  fail "case 3b: a link target with a balanced parenthesis pair was reported: $(cat "$work/err")"
fi

fixture emptynode
: >"$dir/docs/features/billing.md"
lint
expect "case 8e empty node" 1 "docs/features/billing.md:1: no frontmatter"
expect "case 8e count wording" 1 "knowledge-lint: 1 problem"
if grep -q '1 problems' "$work/err"; then
  fail "case 8e: one problem was reported in the plural"
fi

fixture ignoredadr
git -C "$dir" rm -rq --cached docs/adr
printf 'docs/adr/\n' >"$dir/.gitignore"
git -C "$dir" add .gitignore
lint --write
if grep -q '^Decisions:' "$dir/docs/knowledge/index.md"; then
  fail "case 1c: the index points to an untracked, ignored docs/adr"
fi

fixture_glob() {
  fixture "$1"
  mkdir -p "$(dirname "$dir/$3")"
  printf 'x\n' >"$dir/$3"
  node billing Billing "$2" '' ''
  git -C "$dir" add -A
  lint --write
  lint
}

expect_glob_match() {
  fixture_glob "$1" "$2" "$3"
  if grep -qF "$2 matches no file" "$work/err"; then
    fail "$1: $2 should match $3: $(cat "$work/err")"
  fi
}

expect_glob_miss() {
  fixture_glob "$1" "$2" "$3"
  expect "$1" 1 "$2 matches no file"
}

expect_glob_match glob1 'src/*.ts' src/a.ts
expect_glob_miss glob2 'src/*.ts' src/x/a.ts
expect_glob_match glob3 'src/?.ts' src/a.ts
expect_glob_miss glob4 'src/?ts' src/a/ts
expect_glob_match glob5 'src/deep/' src/deep/x/y.ts
expect_glob_miss glob6 'src/deep/' src/deeper/y.ts

fixture nestedbrace
node billing Billing 'src/{a,{b,c}}/**' '' ''
lint
expect "case 15 nested brace" 1 "has an unbalanced or nested brace"
fixture openbrace
node billing Billing 'src/{a,b/**' '' ''
lint
expect "case 15b unbalanced brace" 1 "has an unbalanced or nested brace"

mkdir -p "$work/plain"
work=$(cd "$work" && pwd -P)
status=0
(cd "$work/plain" && GIT_CEILING_DIRECTORIES="$work" "$shipped") >"$work/out" 2>"$work/err" || status=$?
expect "case 10 outside a work tree" 2 "knowledge-lint: not inside a git work tree"

fixture usage
lint --bogus
expect "case 11 unknown argument" 2 "usage: scripts/knowledge-lint.sh [--write]"
lint --write extra
expect "case 11 two arguments" 2 "usage:"

[ -x "$shipped" ] || fail "the shipped knowledge-lint.sh is not executable"

if [ "$failures" -gt 0 ]; then
  exit 1
fi
echo "test-knowledge-lint: ok"
